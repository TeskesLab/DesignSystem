#!/usr/bin/env python3
"""Generate native token values and package-local assets from the canonical source.

Use --check to detect drift without writing. Requires Python 3.10+, gofmt and rustfmt.
"""
import argparse
import json
import subprocess
from pathlib import Path

from build_tokens import flatten, resolve

ROOT = Path(__file__).resolve().parents[1]


def pascal(name):
    return ''.join(part.capitalize() for part in name.split('-'))


def numeric(value):
    if isinstance(value, (int, float)):
        return float(value)
    for suffix, scale in [('rem', 16), ('px', 1), ('ms', 1)]:
        if value.endswith(suffix):
            return float(value[:-len(suffix)]) * scale
    raise ValueError(f'Unsupported native numeric token: {value}')


def outputs():
    source = json.loads((ROOT / 'tokens/source.json').read_text())
    roles = list(source['themes']['light'])
    if set(source['themes']['dark']) != set(roles):
        raise ValueError('Light and dark themes must define the same roles')
    palettes = []
    for mode in ['light', 'dark']:
        colors = []
        for role in roles:
            value = resolve(source['themes'][mode][role], source)
            if len(value) != 7 or not value.startswith('#'):
                raise ValueError(f'Expected opaque RGB color for {mode}/{role}')
            colors.append(tuple(int(value[index:index + 2], 16) for index in (1, 3, 5)))
        palettes.append(colors)
    common = {
        name: numeric(value)
        for name, value in flatten(source['common']).items()
        if name not in {'font-sans', 'font-mono', 'motion-ease'}
    }
    densities = source['density']
    fields = ['control-height', 'row-height', 'control-px', 'control-py']
    comfortable = [densities['comfortable'][name] for name in fields]
    compact = [densities['compact'][name] for name in fields]

    go = [
        '// Code generated by scripts/build_native.py; DO NOT EDIT.',
        'package designsystem', '', 'import "image/color"', '',
        f'const Version = "{source["version"]}"', '',
        'type Scheme uint8', 'const (', '\tLight Scheme = iota', '\tDark', ')', '',
        'type Role uint8', 'const (',
    ]
    go.extend('\t' + pascal(role) + (' Role = iota' if index == 0 else '') for index, role in enumerate(roles))
    go.extend(['\tRoleCount', ')', '', 'var roleNames = [RoleCount]string{'])
    go.extend(f'\t"{role}",' for role in roles)
    go.extend(['}', '', 'var palettes = [2][RoleCount]color.NRGBA{'])
    for colors in palettes:
        go.append('\t{')
        go.extend(f'\t\t{{R: {r}, G: {g}, B: {b}, A: 255}},' for r, g, b in colors)
        go.append('\t},')
    go.extend([
        '}', '',
        '// Color returns false for an invalid scheme or role; palettes cannot be mutated by callers.',
        'func Color(scheme Scheme, role Role) (color.NRGBA, bool) {',
        '\tif scheme > Dark || role >= RoleCount { return color.NRGBA{}, false }',
        '\treturn palettes[scheme][role], true', '}', '',
        'func RoleName(role Role) (string, bool) {',
        '\tif role >= RoleCount { return "", false }',
        '\treturn roleNames[role], true', '}', '',
        'type Density uint8', 'const (', '\tComfortable Density = iota', '\tCompact', ')', '',
        'type Metrics struct {', '\tControlHeight, RowHeight, ControlPaddingX, ControlPaddingY float32', '}', '',
        '// Dimensions preserves comfortable targets for touch input.',
        'func Dimensions(density Density, touch bool) Metrics {',
        '\tif density == Compact && !touch {',
        '\t\treturn Metrics{' + ', '.join(map(str, compact)) + '}', '\t}',
        '\treturn Metrics{' + ', '.join(map(str, comfortable)) + '}', '}', '',
        '// Numeric tokens use logical pixels, milliseconds, and unitless weights/line heights.', 'const (',
    ])
    go.extend(f'\t{pascal(name)} = {value:g}' for name, value in common.items())
    go.extend([')', ''])

    rust = [
        '// Generated by scripts/build_native.py; DO NOT EDIT.',
        f'pub const VERSION: &str = "{source["version"]}";', '',
        '#[derive(Clone, Copy, Debug, Eq, PartialEq)]', '#[repr(usize)]',
        'pub enum Scheme { Light, Dark }', '',
        '#[derive(Clone, Copy, Debug, Eq, PartialEq)]', '#[repr(usize)]', 'pub enum Role {',
    ]
    rust.extend(f'    {pascal(role)},' for role in roles)
    rust.extend(['}', '', 'impl Role {', f'    pub const ALL: [Self; {len(roles)}] = ['])
    rust.extend(f'        Self::{pascal(role)},' for role in roles)
    rust.extend(['    ];', '    pub const fn name(self) -> &\'static str {', '        match self {'])
    rust.extend(f'            Self::{pascal(role)} => "{role}",' for role in roles)
    rust.extend([
        '        }', '    }', '}', '',
        '#[derive(Clone, Copy, Debug, Eq, PartialEq)]',
        'pub struct Rgba { pub r: u8, pub g: u8, pub b: u8, pub a: u8 }', '',
        f'const PALETTES: [[Rgba; {len(roles)}]; 2] = [',
    ])
    for colors in palettes:
        rust.append('    [')
        rust.extend(f'        Rgba {{ r: {r}, g: {g}, b: {b}, a: 255 }},' for r, g, b in colors)
        rust.append('    ],')
    rust.extend([
        '];', '',
        'pub const fn color(scheme: Scheme, role: Role) -> Rgba {',
        '    PALETTES[scheme as usize][role as usize]', '}', '',
        '#[derive(Clone, Copy, Debug, Eq, PartialEq)]',
        'pub enum Density { Comfortable, Compact }', '',
        '#[derive(Clone, Copy, Debug, PartialEq)]',
        'pub struct Metrics {',
        '    pub control_height: f32,', '    pub row_height: f32,',
        '    pub control_padding_x: f32,', '    pub control_padding_y: f32,', '}', '',
        'pub const fn dimensions(density: Density, touch: bool) -> Metrics {',
        '    match (density, touch) {',
    ])
    for pattern, values in [('(Density::Compact, false)', compact), ('_', comfortable)]:
        rust.append(f'        {pattern} => Metrics {{ control_height: {values[0]:.1f}, row_height: {values[1]:.1f}, control_padding_x: {values[2]:.1f}, control_padding_y: {values[3]:.1f} }},')
    rust.extend(['    }', '}', '', '// Logical pixels, milliseconds, and unitless weights/line heights.'])
    for name, value in common.items():
        number = f'{value:g}'
        if '.' not in number:
            number += '.0'
        rust.append(f'pub const {name.replace("-", "_").upper()}: f32 = {number};')
    rust.append('')

    generated = {
        'go/tokens_generated.go': subprocess.run(
            ['gofmt'], input='\n'.join(go).encode(), stdout=subprocess.PIPE, check=True
        ).stdout,
        'rust/src/tokens.rs': subprocess.run(
            ['rustfmt', '--edition', '2024', '--emit', 'stdout'],
            input='\n'.join(rust).encode(), stdout=subprocess.PIPE, check=True
        ).stdout,
    }
    for target in ['go', 'rust']:
        for filename in ['IBMPlexSans-Regular.ttf', 'IBMPlexSans-SemiBold.ttf', 'IBMPlexMono-Regular.ttf', 'OFL-IBM-Plex.txt']:
            generated[f'{target}/fonts/{filename}'] = (ROOT / 'assets/fonts' / filename).read_bytes()
        for filename in ['LICENSE', 'LICENSE-CC-BY-SA-4.0.txt']:
            generated[f'{target}/{filename}'] = (ROOT / filename).read_bytes()
    return generated


def generate(check=False):
    stale = []
    for name, content in outputs().items():
        path = ROOT / name
        if path.exists() and path.read_bytes() == content:
            continue
        if check:
            stale.append(name)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
    if stale:
        raise SystemExit('Native generated files differ: ' + ', '.join(stale))
    print('Native token sources and bundled assets ' + ('match the canonical source.' if check else 'generated.'))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail on generated source or asset drift without writing')
    args = parser.parse_args()
    generate(args.check)


if __name__ == '__main__':
    main()
